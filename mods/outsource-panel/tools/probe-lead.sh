check_a3() { # $.store across quit and --resume of the same session id
  local f sid set_line
  ensure_session 1 || {
    record MISMATCH A3 "no prompt appeared within 60 s"
    return
  }
  dismiss_dialog a1
  send_keys '/probe store' a1
  enter a1
  if ! f="$(wait_transcript 'PROBE-STORE-SET' 60)"; then
    record MISMATCH A3 "'/probe store' left no transcript trace"
    return
  fi
  sleep 3
  cap a3-set a1
  # The pane prints the command's own reply; the transcript stores it in a
  # system row with the text in a different field, so the pane line is the
  # primary source and the transcript the fallback.
  set_line="$(pane a1 | grep -m1 'PROBE-STORE-SET' || true)"
  sid="$(printf '%s' "$set_line" | sed -n 's/.*"sid":"\([^"]*\)".*/\1/p')"
  if [ -z "$sid" ]; then
    sid="$(python3 -c '
import json, re, sys

def texts(row):
    msg = row.get("message") or {}
    c = msg.get("content")
    if isinstance(c, str):
        yield c
    elif isinstance(c, list):
        for b in c:
            if isinstance(b, dict) and isinstance(b.get("text"), str):
                yield b["text"]

for line in open(sys.argv[1], encoding="utf-8", errors="replace"):
    if "PROBE-STORE-SET" not in line:
        continue
    try:
        row = json.loads(line)
    except Exception:
        continue
    for t in texts(row):
        m = re.search(r"\{.*\}", t)
        if not m:
            continue
        try:
            sid = json.loads(m.group(0)).get("sid")
        except Exception:
            continue
        if isinstance(sid, str) and sid:
            print(sid)
            sys.exit(0)
sys.exit(1)' "$f" || true)"
  fi
  if [ -z "$sid" ]; then
    record MISMATCH A3 "could not read the session id from the transcript (pane: $set_line)"
    return
  fi
  send_keys '/exit' a1
  enter a1
  sleep 3
  # Resume the same session id with the same probe mod.
  tmux -L "$SRV" kill-session -t a1 2>/dev/null || true
  tmux -L "$SRV" new-session -d -s a3 -x 160 -y 50 -c "$WORK" \
    "env -u CLAUDE_CODE_MESSAGING_SOCKET -u CLAUDE_CODE_MESSAGING_TOKEN -u CLAUDE_CODE_SESSION_ID -u CLAUDE_CODE_CHILD_SESSION -u OUTSOURCE_ROUND -u OUTSOURCE_DETACHED CLAUDE_CONFIG_DIR='$CFG' ${MODEL_ENV[*]} claude --resume '$sid' --plugin-dir '$PROBE' --permission-mode bypassPermissions --debug-file '$WD/debug-a3.log'"
  if ! wait_ready a3; then
    record MISMATCH A3 "the resumed session never showed a prompt"
    return
  fi
  dismiss_dialog a3
  if ! f="$(wait_transcript 'PROBE-STORE-READBACK' 60)"; then
    cap a3 a3
    record MISMATCH A3 "no PROBE-STORE-READBACK row after resume (see $CAPS/a3.txt)"
    return
  fi
  cap a3 a3
  local line
  # A session.append notice is a system row: the text sits in the top-level
  # content field, not under message.
  line="$(grep -m1 'PROBE-STORE-READBACK' "$f" | python3 -c 'import json,sys
try:
    row = json.loads(sys.stdin.read())
    c = row.get("content")
    if not isinstance(c, str):
        msg = row.get("message") or {}
        c = msg.get("content")
    text = c if isinstance(c, str) else " ".join(str(b.get("text")) for b in (c or []) if isinstance(b, dict))
    print(text[:220])
except Exception:
    print("(unparseable)")')"
  echo "$line" >"$CAPS/a3-evidence.txt"
  if printf '%s' "$line" | grep -q 'sameSid=true' && printf '%s' "$line" | grep -q "\"sid\":\"$sid\""; then
    record MATCH A3 "store survived the restart; resumed session id is the same: $(printf '%s' "$line" | cut -c1-120)"
  else
    record MISMATCH A3 "$line"
  fi
}

